# Syntax of ImageMagick 6 `convert` (convert-im6.q16, 6.9.12-98), derived from the
# manual page and verified against the binary.
#
#   convert [options...] input-file... [options...] output-file
#
# Notes:
# - Every option is a single word with one leading "-" (long names, no "=" form, no
#   bundling). Most options also have a "+" form; where the "+" form takes the same
#   argument it is given as an alias, where it takes none it is a separate Flag.
# - Options may appear anywhere, interleaved with the operands; the LAST operand is the
#   output file, every other operand is an input file. "-" (or "fmt:-") as an input
#   means standard input, as the output it means standard output.
# - "(" and ")" may appear as operands to delimit an image sub-list (not modelled).
# - Eleven options take TWO arguments (-annotate, -copy, -distort, -evaluate, -floodfill,
#   -function, -limit, -morphology, -set, -sparse-color, -statistic, and the "+" forms of
#   -distort, -morphology and -sparse-color). The node below describes the first argument;
#   the second one is noted in a trailing comment because the format has no two-argument
#   value node.
# - The man page lists "-connected-component" but the binary only accepts
#   "-connected-components". The binary additionally accepts the undocumented
#   -average, -cache, -concurrent, -duration, -gaussian, -linewidth, -maximum, -minimum,
#   -noop and -recolor, and the documented-elsewhere -metric.

